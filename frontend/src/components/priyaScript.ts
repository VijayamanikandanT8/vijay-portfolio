// ---- cursive engine: centre-lines -> smoothed, tangent-joined, pen-pressure ink ----
type Pt = [number, number];

const LEAN = 0; // upright letters, no slant
const JOIN_MAX = 16; // only strokes of the SAME letter that nearly touch are joined; letters stay separate // letters up to 120 units apart are linked, so the writing flows
const FLOURISH = false; // no cursive lead-in / exit hairlines
const NIB = (32 * Math.PI) / 180; // pen angle
const W_MAX = 11; // softer thick strokes
const W_MIN = 7; // thin strokes stay fuller, so there is less sharp contrast
const W_HAIR = 5; // links between letters are not hairline-thin

const parse = (s: string): Pt[] => s.split(" ").map((t) => t.split(",").map(Number) as Pt);

const resample = (pts: Pt[], step: number): Pt[] => {
  const out: Pt[] = [pts[0]];
  let carry = 0;
  for (let i = 0; i < pts.length - 1; i++) {
    const [ax, ay] = pts[i];
    const [bx, by] = pts[i + 1];
    const L = Math.hypot(bx - ax, by - ay);
    let t = step - carry;
    while (t <= L) {
      out.push([ax + ((bx - ax) * t) / L, ay + ((by - ay) * t) / L]);
      t += step;
    }
    carry = L - (t - step);
  }
  const last = pts[pts.length - 1];
  const e = out[out.length - 1];
  if (Math.hypot(last[0] - e[0], last[1] - e[1]) > step * 0.4) out.push(last);
  else out[out.length - 1] = last;
  return out;
};

const relax = (pts: Pt[], passes: number): Pt[] => {
  let p = pts;
  for (let k = 0; k < passes; k++) {
    p = p.map((q, i) =>
      i === 0 || i === p.length - 1
        ? q
        : ([p[i - 1][0] * 0.25 + q[0] * 0.5 + p[i + 1][0] * 0.25, p[i - 1][1] * 0.25 + q[1] * 0.5 + p[i + 1][1] * 0.25] as Pt)
    );
  }
  return p;
};

const unit = (a: Pt, b: Pt): Pt => {
  const d = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
  return [(b[0] - a[0]) / d, (b[1] - a[1]) / d];
};

const bezier = (p0: Pt, p1: Pt, p2: Pt, p3: Pt, n: number): Pt[] => {
  const o: Pt[] = [];
  for (let i = 1; i <= n; i++) {
    const t = i / n;
    const u = 1 - t;
    o.push([
      u * u * u * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t * t * t * p3[0],
      u * u * u * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t * t * t * p3[1],
    ]);
  }
  return o;
};

interface Run {
  pts: Pt[];
  hair: boolean[]; // true where the point belongs to a connector / lead-in / flourish
}

// one word -> flowing runs. Letters whose pen-lift is short become ONE continuous line.
const buildRuns = (strokes: string[], baseY: number): { runs: Run[]; dots: Pt[] } => {
  const lean = (p: Pt): Pt => [p[0] + (baseY - p[1]) * LEAN, p[1]];
  const all = strokes.map(parse);
  const dots = all.filter((s) => s.length === 1).map((s) => lean(s[0]));
  const lines = all.filter((s) => s.length > 1).map((s) => relax(resample(s.map(lean), 4), 12));

  const runs: Run[] = [];
  let cur: Run | null = null;
  for (const s of lines) {
    if (cur) {
      const e = cur.pts[cur.pts.length - 1];
      const b = s[0];
      const d = Math.hypot(b[0] - e[0], b[1] - e[1]);
      // only join forward-flowing, modest pen movements (no backtracking spikes)
      if (d < JOIN_MAX) {
        const te = unit(cur.pts[Math.max(0, cur.pts.length - 6)], e);
        const tb = unit(b, s[Math.min(5, s.length - 1)]);
        const k = Math.max(22, d * 0.38);
        // the pen swings down-and-through before it climbs into the next letter
        const back = Math.max(0, e[0] - b[0]); // how far the pen must travel backwards
        const dip = 8 + d * 0.1 + back * 0.5; // backward links swing below the baseline like a real ligature
        const c = bezier(
          e,
          [e[0] + te[0] * k + back * 0.35, e[1] + te[1] * k + dip],
          [b[0] - tb[0] * k - back * 0.35, b[1] - tb[1] * k + dip],
          b,
          Math.max(12, Math.round(d / 4))
        );
        cur.pts.push(...c.slice(0, -1), ...s);
        cur.hair.push(...c.slice(0, -1).map(() => true), ...s.map(() => false));
        continue;
      }
      runs.push(cur);
    }
    cur = { pts: s.slice(), hair: s.map(() => false) };
  }
  if (cur) runs.push(cur);

  // lead-in hairline before every run and a flicked, tapering exit after it
  for (const r of runs.filter(() => FLOURISH)) {
    const a = r.pts[0];
    const ta = unit(a, r.pts[Math.min(6, r.pts.length - 1)]);
    const lead = bezier(
      [a[0] - 40 - ta[0] * 8, a[1] + 22],
      [a[0] - 22, a[1] + 16],
      [a[0] - ta[0] * 20, a[1] - ta[1] * 20],
      a,
      9
    );
    const n = r.pts.length;
    const z = r.pts[n - 1];
    const tz = unit(r.pts[Math.max(0, n - 6)], z);
    const exit = bezier(z, [z[0] + tz[0] * 26, z[1] + tz[1] * 26], [z[0] + 56, z[1] - 6], [z[0] + 96, z[1] - 30], 12);
    r.pts = [[a[0] - 40 - ta[0] * 8, a[1] + 22], ...lead, ...r.pts.slice(1), ...exit];
    r.hair = [true, ...lead.map(() => true), ...r.hair.slice(1), ...exit.map(() => true)];
  }
  return { runs, dots };
};

const f = (n: number) => n.toFixed(1);

// centre-line of a run as a smooth path (this is what the pen animation traces)
const linePath = (pts: Pt[]) => {
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const a = pts[i - 1] ?? pts[i];
    const b = pts[i];
    const c = pts[i + 1];
    const e = pts[i + 2] ?? c;
    d += `C${f(b[0] + (c[0] - a[0]) / 6)} ${f(b[1] + (c[1] - a[1]) / 6)} ${f(c[0] - (e[0] - b[0]) / 6)} ${f(c[1] - (e[1] - b[1]) / 6)} ${f(c[0])} ${f(c[1])}`;
  }
  return d;
};

// pressure-sensitive ink ribbon around a run: broad-nib contrast + taper + hairline joins
const inkPath = (r: Run) => {
  const { pts, hair } = r;
  const n = pts.length;
  const seg: number[] = [0];
  for (let i = 1; i < n; i++) seg.push(seg[i - 1] + Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]));
  const total = seg[n - 1] || 1;
  const w: number[] = [];
  for (let i = 0; i < n; i++) {
    const a = pts[Math.max(0, i - 2)];
    const b = pts[Math.min(n - 1, i + 2)];
    const th = Math.atan2(b[1] - a[1], b[0] - a[0]);
    const nib = W_MIN + (W_MAX - W_MIN) * Math.abs(Math.sin(th - NIB));
    let v = hair[i] ? W_HAIR : nib;
    const edge = Math.min(seg[i], total - seg[i]);
    v *= 0.22 + 0.78 * Math.min(1, edge / 60); // pen lands and lifts softly
    w.push(Math.max(1.8, v));
  }
  // smooth the width so thick/thin never jumps
  for (let k = 0; k < 8; k++) for (let i = 1; i < n - 1; i++) w[i] = w[i - 1] * 0.25 + w[i] * 0.5 + w[i + 1] * 0.25;
  const L: Pt[] = [];
  const R: Pt[] = [];
  for (let i = 0; i < n; i++) {
    const a = pts[Math.max(0, i - 4)];
    const b = pts[Math.min(n - 1, i + 4)];
    const t = unit(a, b);
    L.push([pts[i][0] - t[1] * (w[i] / 2), pts[i][1] + t[0] * (w[i] / 2)]);
    R.push([pts[i][0] + t[1] * (w[i] / 2), pts[i][1] - t[0] * (w[i] / 2)]);
  }
  // curved (quadratic) edges instead of straight polygon segments
  const smooth = (P: Pt[]) => {
    let d = "";
    for (let i = 1; i < P.length - 1; i++) {
      const mx = (P[i][0] + P[i + 1][0]) / 2;
      const my = (P[i][1] + P[i + 1][1]) / 2;
      d += `Q${f(P[i][0])} ${f(P[i][1])} ${f(mx)} ${f(my)}`;
    }
    const z = P[P.length - 1];
    return d + `L${f(z[0])} ${f(z[1])}`;
  };
  const Rr = R.slice().reverse();
  return `M${f(L[0][0])} ${f(L[0][1])}` + smooth(L) + `L${f(Rr[0][0])} ${f(Rr[0][1])}` + smooth(Rr) + "Z";
};

const dotInk = ([x, y]: Pt) => `M${f(x - 9)} ${f(y)}a9 9 0 1 0 18 0a9 9 0 1 0 -18 0Z`;
const dotLine = ([x, y]: Pt) => `M${f(x)} ${f(y)}l0.1 0.1`;

const writeWord = (strokes: string[], baseY: number) => {
  const { runs, dots } = buildRuns(strokes, baseY);
  const xs = runs.flatMap((r) => r.pts.map((p) => p[0]));
  return {
    lines: [...runs.map((r) => linePath(r.pts)), ...dots.map(dotLine)],
    ink: [...runs.map(inkPath), ...dots.map(dotInk)].join(""),
    x: [Math.floor(Math.min(...xs, ...dots.map((d) => d[0])) - 24), Math.ceil(Math.max(...xs, ...dots.map((d) => d[0])) + 24)] as [number, number],
  };
};

